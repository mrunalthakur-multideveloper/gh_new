-- PostgreSQL / NeonDB Database Schema for Greenhouse Scraped Jobs
-- Table name: links
-- Source: greenhouse2

CREATE TABLE IF NOT EXISTS links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id TEXT NOT NULL,
    title TEXT,
    company_name TEXT,
    company_url TEXT,
    company_logo TEXT,
    location_city TEXT,
    location_state TEXT,
    location_country TEXT,
    location_display TEXT,
    description TEXT,
    date_posted DATE,
    scraped_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    job_url TEXT,
    apply_url TEXT,
    job_type TEXT,
    job_level TEXT,
    company_industry TEXT,
    job_function TEXT,
    is_remote BOOLEAN DEFAULT false,
    is_easy_apply BOOLEAN DEFAULT false,
    compensation_min NUMERIC,
    compensation_max NUMERIC,
    compensation_currency TEXT DEFAULT 'USD',
    compensation_interval TEXT DEFAULT 'yearly',
    emails TEXT,
    search_keyword TEXT,
    experience TEXT,
    salary_text TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    skills TEXT,
    sponsorship_h1b TEXT,
    source TEXT DEFAULT 'greenhouse2',
    experience_max SMALLINT,
    experience_min SMALLINT,
    
    -- Constraints
    CONSTRAINT linkedin_jobs_job_id_key UNIQUE (job_id)
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_linkedin_jobs_apply_url ON links USING BTREE (apply_url);
CREATE INDEX IF NOT EXISTS idx_linkedin_jobs_created_at ON links USING BTREE (created_at);
CREATE INDEX IF NOT EXISTS idx_linkedin_jobs_job_id ON links USING BTREE (job_id);
CREATE INDEX IF NOT EXISTS idx_linkedin_jobs_search_keyword ON links USING BTREE (search_keyword);
CREATE INDEX IF NOT EXISTS idx_links_job_id ON links USING BTREE (job_id);
