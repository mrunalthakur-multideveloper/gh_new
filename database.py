"""
PostgreSQL Database Connection & Upsert Manager.
Handles table initialization, indexing, and batch upsert operations.
"""

import os
import logging
from typing import List, Dict, Any, Optional
import psycopg2
from psycopg2.extras import execute_values
from dotenv import load_dotenv

load_dotenv()
logger = logging.getLogger("greenhouse_db")

TABLE_COLUMNS = [
    "job_id", "title", "company_name", "company_url", "company_logo",
    "location_city", "location_state", "location_country", "location_display",
    "description", "date_posted", "scraped_at", "job_url", "apply_url",
    "job_type", "job_level", "company_industry", "job_function",
    "is_remote", "is_easy_apply", "compensation_min", "compensation_max",
    "compensation_currency", "compensation_interval", "emails",
    "search_keyword", "experience", "salary_text", "skills",
    "sponsorship_h1b", "source", "experience_max", "experience_min"
]


class DatabaseManager:
    def __init__(self, db_url: Optional[str] = None, table_name: str = "links"):
        self.db_url = db_url or os.getenv("DATABASE_URL")
        self.table_name = table_name

    def is_configured(self) -> bool:
        return bool(self.db_url and self.db_url.strip())

    def get_connection(self):
        """Creates a PostgreSQL/NeonDB connection with proper SSL configuration."""
        if not self.is_configured():
            raise ValueError("DATABASE_URL is not configured.")
        
        conn_str = self.db_url.strip()
        # Ensure sslmode=require for NeonDB if not specified
        if "neon.tech" in conn_str and "sslmode" not in conn_str:
            delimiter = "&" if "?" in conn_str else "?"
            conn_str = f"{conn_str}{delimiter}sslmode=require"
            
        return psycopg2.connect(conn_str)

    def init_database(self, schema_file: str = "schema.sql") -> bool:
        """Runs the schema.sql script to ensure table and indexes exist in NeonDB."""
        if not self.is_configured():
            logger.warning("Database URL is not configured. Skipping DB initialization.")
            return False

        try:
            with self.get_connection() as conn:
                with conn.cursor() as cur:
                    if os.path.exists(schema_file):
                        with open(schema_file, "r", encoding="utf-8") as f:
                            sql = f.read()
                            if self.table_name != "linkedin_jobs":
                                sql = sql.replace("linkedin_jobs", self.table_name)
                            cur.execute(sql)
                    else:
                        cur.execute(f"""
                        CREATE TABLE IF NOT EXISTS {self.table_name} (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            job_id TEXT UNIQUE NOT NULL,
                            title TEXT,
                            company_name TEXT,
                            company_url TEXT,
                            company_logo TEXT,
                            location_city TEXT,
                            location_state TEXT,
                            location_country TEXT,
                            location_display TEXT,
                            description TEXT,
                            date_posted DATE,
                            scraped_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
                            job_url TEXT,
                            apply_url TEXT,
                            job_type TEXT,
                            job_level TEXT,
                            company_industry TEXT,
                            job_function TEXT,
                            is_remote BOOLEAN DEFAULT false,
                            is_easy_apply BOOLEAN DEFAULT false,
                            compensation_min NUMERIC,
                            compensation_max NUMERIC,
                            compensation_currency TEXT DEFAULT 'USD',
                            compensation_interval TEXT DEFAULT 'yearly',
                            emails TEXT,
                            search_keyword TEXT,
                            experience TEXT,
                            salary_text TEXT,
                            created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
                            skills TEXT,
                            sponsorship_h1b TEXT,
                            source TEXT DEFAULT 'greenhouse2',
                            experience_max SMALLINT,
                            experience_min SMALLINT
                        );
                        CREATE INDEX IF NOT EXISTS idx_{self.table_name}_apply_url ON {self.table_name} (apply_url);
                        CREATE INDEX IF NOT EXISTS idx_{self.table_name}_created_at ON {self.table_name} (created_at);
                        CREATE INDEX IF NOT EXISTS idx_{self.table_name}_job_id ON {self.table_name} (job_id);
                        CREATE INDEX IF NOT EXISTS idx_{self.table_name}_search_keyword ON {self.table_name} (search_keyword);
                        """)
                conn.commit()
            logger.info(f"NeonDB table '{self.table_name}' and indexes initialized successfully.")
            return True
        except Exception as e:
            logger.error(f"Failed to initialize NeonDB database: {e}")
            return False

    def upsert_jobs(self, jobs: List[Dict[str, Any]]) -> int:
        """
        Performs batch upsert of jobs into the PostgreSQL table.
        Returns number of affected rows.
        """
        if not jobs or not self.is_configured():
            return 0

        # Build upsert query
        cols_str = ", ".join(TABLE_COLUMNS)
        
        # Build update set expressions (excluding job_id and created_at)
        update_assignments = [
            f"{col} = EXCLUDED.{col}" for col in TABLE_COLUMNS if col not in ("job_id", "created_at")
        ]
        update_str = ", ".join(update_assignments)

        query = f"""
        INSERT INTO {self.table_name} ({cols_str})
        VALUES %s
        ON CONFLICT (job_id) DO UPDATE SET
            {update_str}
        """

        # Prepare values
        values = []
        for job in jobs:
            row = tuple(job.get(col) for col in TABLE_COLUMNS)
            values.append(row)

        try:
            with self.get_connection() as conn:
                with conn.cursor() as cur:
                    execute_values(cur, query, values, page_size=100)
                conn.commit()
            return len(values)
        except Exception as e:
            logger.error(f"Error upserting jobs into NeonDB: {e}")
            raise e
